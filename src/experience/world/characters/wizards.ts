import * as THREE from "three";
import { ORB_Y, type CastingCircle } from "../arena";
import {
  createGlowSprite,
  hdrColor,
  type FrameTime,
  type WorldBuildContext,
  type WorldState,
} from "../buildContext";
import * as guardianTurnaround from "./turnarounds/guardian";
import * as mageTurnaround from "./turnarounds/mage";
import * as mysticTurnaround from "./turnarounds/mystic";
import * as scholarTurnaround from "./turnarounds/scholar";
import { createSpringBones, type SpringBones } from "./springBones";
import {
  paintWithTurnaround,
  projectTurnaround,
  type Turnaround,
} from "./turnaroundProjection";
import { WIZARD_CLASSES, type WizardClassId } from "./wizardClasses";
import {
  BASE_STANCE,
  CAST_RELEASE_SECONDS,
  classStance,
  createWizardClips,
  type WizardClips,
} from "./wizardClips";
import {
  CAPE_BONES,
  CAPE_END_OFFSET,
  COAT_CHAINS,
  COAT_END_OFFSET,
  createWizardGeometry,
  createWizardSkeleton,
  GUARDIAN_SHIELD,
  REST_POSITION,
  WIZARD_GLOWS,
  type BoneName,
  type GlowAnchor,
} from "./wizardRig";

/** Each class's concept-sheet turnaround (generated by tools/paperdoll/bake_turnaround.py). */
const TURNAROUNDS: Record<
  WizardClassId,
  { atlas: string; turnaround: Turnaround }
> = {
  mage: { atlas: mageTurnaround.ATLAS, turnaround: mageTurnaround.TURNAROUND },
  guardian: {
    atlas: guardianTurnaround.ATLAS,
    turnaround: guardianTurnaround.TURNAROUND,
  },
  mystic: {
    atlas: mysticTurnaround.ATLAS,
    turnaround: mysticTurnaround.TURNAROUND,
  },
  scholar: {
    atlas: scholarTurnaround.ATLAS,
    turnaround: scholarTurnaround.TURNAROUND,
  },
};

/** World units per metre of wizard: a 1.8 m wizard stands about 4.6 units tall on a 5.8-unit circle. */
const WIZARD_SCALE = 2.7;
const HEAD_HEIGHT = 1.62;
const APPEAR_SECONDS = 0.4;
const BOLT_SECONDS = 0.5;
const BOLT_TRAIL_LENGTH = 6;
const ADDITIVE = THREE.AdditiveBlending;

interface GlowSprite {
  sprite: THREE.Sprite;
  anchor: GlowAnchor;
  baseColor: THREE.Color;
}

interface Bolt {
  head: THREE.Sprite;
  trail: THREE.Sprite[];
  start: THREE.Vector3;
  middle: THREE.Vector3;
  progress: number;
  isFlying: boolean;
}

interface Wizard {
  classId: WizardClassId;
  circleIndex: number;
  group: THREE.Group;
  bones: Record<BoneName, THREE.Bone>;
  skeleton: THREE.Skeleton;
  mixer: THREE.AnimationMixer;
  idle: THREE.AnimationAction;
  enter: THREE.AnimationAction;
  cast: THREE.AnimationAction;
  flourish: THREE.AnimationAction;
  /** The enter, cast or flourish action that is playing over the idle, if any. */
  oneShot: THREE.AnimationAction | null;
  hasReleasedSpell: boolean;
  /** The next cast is the one that shows the character off after it was chosen. */
  isShowingOff: boolean;
  springs: SpringBones;
  castGlow: GlowSprite;
  extraGlows: GlowSprite[];
  flash: THREE.Sprite;
  shield: THREE.Mesh<THREE.BufferGeometry, THREE.MeshBasicMaterial> | null;
  bolt: Bolt;
  age: number;
  nextIdleBreakAt: number;
  lookTarget: THREE.Vector3;
  lookUntil: number;
  lookYaw: number;
  lookPitch: number;
  lookWeight: number;
  /** The neck and head rotations as the clips left them, before the look was added. */
  animatedNeck: THREE.Quaternion;
  animatedHead: THREE.Quaternion;
  phase: number;
}

const easeOutBack = (k: number) =>
  1 + 2.7 * Math.pow(k - 1, 3) + 1.7 * Math.pow(k - 1, 2);
const smoothstep = (k: number) => {
  const clamped = THREE.MathUtils.clamp(k, 0, 1);
  return clamped * clamped * (3 - 2 * clamped);
};

/**
 * Lets a material glow faintly in its own colours, so the wizards stay readable against the
 * night sky wherever the moonlight falls.
 */
function withSelfLight(material: THREE.MeshStandardMaterial, amount: number) {
  material.onBeforeCompile = (shader) => {
    shader.fragmentShader = shader.fragmentShader.replace(
      "#include <emissivemap_fragment>",
      `#include <emissivemap_fragment>
      totalEmissiveRadiance += diffuseColor.rgb * ${amount.toFixed(2)};`,
    );
  };
  material.customProgramCacheKey = () => `wizard-self-light-${amount}`;
  return material;
}

/**
 * The wizards who stand on the casting circles. Each one is a skinned character driven by three
 * layers: baked clips (stance, entrance, cast), a head that turns to look at things, and spring
 * physics on the cloak and coat.
 */
export function buildWizards(
  { scene, reducedMotion, glowTexture }: WorldBuildContext,
  arena: THREE.Group,
  circles: CastingCircle[],
  state: WorldState,
  camera: THREE.Camera,
) {
  // One material per layer, shared by every wizard; vertex colours carry each class's palette.
  const materials = [
    withSelfLight(
      new THREE.MeshStandardMaterial({
        vertexColors: true,
        flatShading: true,
        roughness: 0.78,
        side: THREE.DoubleSide,
      }),
      0.3,
    ),
    withSelfLight(
      new THREE.MeshStandardMaterial({
        vertexColors: true,
        flatShading: true,
        roughness: 0.34,
        metalness: 1,
        side: THREE.DoubleSide,
      }),
      0.2,
    ),
    new THREE.MeshBasicMaterial({ vertexColors: true }),
  ];
  // Every wizard is painted from its concept sheet: the turnaround is projected onto its model (see
  // turnaroundProjection.ts). The painting already carries its shading, so the surface is smooth and
  // self-lit a little, keeping the sheet's colours at night. Made on first use, per class.
  const painted = new Map<
    WizardClassId,
    { texture: THREE.Texture; materials: THREE.Material[] }
  >();
  function paintedMaterials(classId: WizardClassId) {
    const existing = painted.get(classId);
    if (existing) return existing.materials;
    const texture = new THREE.TextureLoader().load(TURNAROUNDS[classId].atlas);
    texture.colorSpace = THREE.SRGBColorSpace;
    texture.anisotropy = 4;
    const classMaterials = [
      paintWithTurnaround(
        new THREE.MeshStandardMaterial({
          vertexColors: true,
          roughness: 0.85,
          side: THREE.DoubleSide,
          // the painting keeps its own colours instead of fading into the night haze
          fog: false,
        }),
        texture,
        0.5,
      ),
      paintWithTurnaround(
        new THREE.MeshStandardMaterial({
          vertexColors: true,
          roughness: 0.45,
          metalness: 0.55,
          side: THREE.DoubleSide,
          fog: false,
        }),
        texture,
        0.4,
      ),
      materials[2],
    ];
    painted.set(classId, { texture, materials: classMaterials });
    return classMaterials;
  }
  const geometries = new Map<WizardClassId, THREE.BufferGeometry>();
  const clips = new Map<WizardClassId, WizardClips>();
  const shieldShape = new THREE.Shape(
    GUARDIAN_SHIELD.outline.map(([x, y]) => new THREE.Vector2(x, y)),
  );
  const shieldGeometry = new THREE.ShapeGeometry(shieldShape).rotateX(
    Math.PI / 2,
  );
  const shieldRimGeometry = new THREE.BufferGeometry()
    .setFromPoints(shieldShape.getPoints())
    .rotateX(Math.PI / 2);

  const slots: (Wizard | null)[] = circles.map(() => null);
  let onShowOffCast: ((circleIndex: number) => void) | null = null;

  const orbPosition = new THREE.Vector3();
  const impact = createGlowSprite(0xffffff, 3, 1, glowTexture);
  impact.visible = false;
  scene.add(impact);
  let impactAge = 1;

  const scratch = new THREE.Vector3();
  const boltPosition = new THREE.Vector3();
  const wind = new THREE.Vector3();
  const lookEuler = new THREE.Euler(0, 0, 0, "YXZ");
  const lookTurn = new THREE.Quaternion();
  const identity = new THREE.Matrix4();
  const flameTurn = new THREE.Quaternion();
  const FORWARD = new THREE.Vector3(0, 0, 1);

  function attachGlow(
    bones: Record<BoneName, THREE.Bone>,
    anchor: GlowAnchor,
    classGlow: number,
  ): GlowSprite {
    const sprite = createGlowSprite(
      anchor.color ?? classGlow,
      anchor.intensity,
      anchor.size,
      glowTexture,
    );
    const [restX, restY, restZ] = REST_POSITION[anchor.bone];
    sprite.position.set(
      anchor.at[0] - restX,
      anchor.at[1] - restY,
      anchor.at[2] - restZ,
    );
    bones[anchor.bone].add(sprite);
    return { sprite, anchor, baseColor: sprite.material.color.clone() };
  }

  function spawn(circleIndex: number, classId: WizardClassId) {
    const wizardClass = WIZARD_CLASSES[classId];
    const circle = circles[circleIndex];
    if (!geometries.has(classId)) {
      const geometry = createWizardGeometry(wizardClass);
      // glows (material group 2) keep their own colour
      projectTurnaround(
        geometry,
        TURNAROUNDS[classId].turnaround,
        { front: classStance(wizardClass), neutral: BASE_STANCE },
        [2],
      );
      geometries.set(classId, geometry);
      clips.set(classId, createWizardClips(wizardClass));
    }
    const classClips = clips.get(classId)!;

    const group = new THREE.Group();
    const { bones, skeleton } = createWizardSkeleton();
    group.add(bones.root);
    const body = new THREE.SkinnedMesh(
      geometries.get(classId)!,
      paintedMaterials(classId),
    );
    body.castShadow = body.receiveShadow = true;
    // the pose moves the body outside the rest-pose bounds, and there are only ever four
    body.frustumCulled = false;
    group.add(body);
    body.bind(skeleton, identity);
    group.position.set(circle.x, circle.seal.position.y, circle.z);
    // face the orb at the centre of the arena
    group.rotation.y = Math.atan2(-circle.x, -circle.z);
    group.scale.setScalar(WIZARD_SCALE * 0.05);
    arena.add(group);

    const glows = WIZARD_GLOWS[classId];
    const glowColor = wizardClass.palette.glow;
    const flash = createGlowSprite(glowColor, 2.5, 1, glowTexture);
    flash.position.y = 1;
    group.add(flash);

    let shield: Wizard["shield"] = null;
    if (classId === "guardian") {
      shield = new THREE.Mesh(
        shieldGeometry,
        new THREE.MeshBasicMaterial({
          color: hdrColor(glowColor, 1.1),
          transparent: true,
          opacity: 0.3,
          blending: ADDITIVE,
          depthWrite: false,
          side: THREE.DoubleSide,
        }),
      );
      shield.add(
        new THREE.LineLoop(
          shieldRimGeometry,
          new THREE.LineBasicMaterial({
            color: hdrColor(glowColor, 2.4),
            transparent: true,
            blending: ADDITIVE,
            depthWrite: false,
          }),
        ),
      );
      const [restX, restY, restZ] = REST_POSITION[GUARDIAN_SHIELD.bone];
      shield.position.set(
        GUARDIAN_SHIELD.at[0] - restX,
        GUARDIAN_SHIELD.at[1] - restY,
        GUARDIAN_SHIELD.at[2] - restZ,
      );
      bones[GUARDIAN_SHIELD.bone].add(shield);
    }

    const boltSprite = (intensity: number, size: number) => {
      const sprite = createGlowSprite(glowColor, intensity, size, glowTexture);
      sprite.visible = false;
      scene.add(sprite);
      return sprite;
    };

    const mixer = new THREE.AnimationMixer(group);
    const idle = mixer.clipAction(classClips.idle);
    const enter = mixer.clipAction(classClips.enter);
    idle.play();
    idle.time = Math.random() * classClips.idle.duration;
    idle.setEffectiveWeight(0);
    enter.setLoop(THREE.LoopOnce, 1);
    enter.clampWhenFinished = true;
    enter.play();

    const wizard: Wizard = {
      classId,
      circleIndex,
      group,
      bones,
      skeleton,
      mixer,
      idle,
      enter,
      cast: mixer.clipAction(classClips.cast),
      flourish: mixer.clipAction(classClips.flourish),
      oneShot: enter,
      hasReleasedSpell: false,
      isShowingOff: true,
      springs: createSpringBones(group, [
        {
          bones: CAPE_BONES.map((name) => bones[name]),
          endOffset: new THREE.Vector3(...CAPE_END_OFFSET),
          stiffness: 0.9,
        },
        ...COAT_CHAINS.map((chain) => ({
          bones: chain.map((name) => bones[name]),
          endOffset: new THREE.Vector3(...COAT_END_OFFSET),
          stiffness: 1.8,
        })),
      ]),
      castGlow: attachGlow(bones, glows.cast, glowColor),
      extraGlows: glows.extras.map((anchor) =>
        attachGlow(bones, anchor, glowColor),
      ),
      flash,
      shield,
      bolt: {
        head: boltSprite(4, 1.5),
        trail: Array.from({ length: BOLT_TRAIL_LENGTH }, (_, k) =>
          boltSprite(2.4 - k * 0.3, 1.1 - k * 0.14),
        ),
        start: new THREE.Vector3(),
        middle: new THREE.Vector3(),
        progress: 0,
        isFlying: false,
      },
      age: 0,
      nextIdleBreakAt: 0,
      lookTarget: new THREE.Vector3(),
      lookUntil: 0,
      lookYaw: 0,
      lookPitch: 0,
      lookWeight: 0,
      animatedNeck: bones.neck.quaternion.clone(),
      animatedHead: bones.head.quaternion.clone(),
      phase: Math.random() * 10,
    };

    mixer.addEventListener("finished", (event) => {
      if (event.action !== wizard.oneShot) return;
      // settle back into the idle stance
      idle.enabled = true;
      idle.setEffectiveWeight(1);
      idle.crossFadeFrom(event.action, 0.4, false);
      wizard.oneShot = null;
      wizard.nextIdleBreakAt =
        state.time + (wizard.isShowingOff ? 0.25 : 5 + Math.random() * 5);
    });
    return wizard;
  }

  function remove(wizard: Wizard) {
    wizard.mixer.stopAllAction();
    wizard.mixer.uncacheRoot(wizard.group);
    wizard.group.traverse((object) => {
      const { material, isSprite, isLine } = object as THREE.Sprite & {
        isLine?: boolean;
      };
      if (isSprite || isLine || object === wizard.shield) material.dispose();
    });
    wizard.group.removeFromParent();
    wizard.skeleton.dispose();
    [wizard.bolt.head, ...wizard.bolt.trail].forEach((sprite) => {
      sprite.removeFromParent();
      sprite.material.dispose();
    });
  }

  /** Plays the enter, cast or flourish clip once over the idle. */
  function playOnce(wizard: Wizard, action: THREE.AnimationAction) {
    action.reset();
    action.setLoop(THREE.LoopOnce, 1);
    action.clampWhenFinished = true;
    action.play();
    action.crossFadeFrom(wizard.idle, 0.2, false);
    wizard.oneShot = action;
    wizard.hasReleasedSpell = false;
  }

  function releaseSpell(wizard: Wizard) {
    const { bolt } = wizard;
    wizard.castGlow.sprite.getWorldPosition(bolt.start);
    bolt.middle.lerpVectors(bolt.start, orbPosition, 0.5);
    bolt.middle.y += 2.6;
    bolt.progress = 0;
    bolt.isFlying = true;
    if (wizard.isShowingOff) {
      wizard.isShowingOff = false;
      onShowOffCast?.(wizard.circleIndex);
    }
  }

  const bezier = (bolt: Bolt, t: number, out: THREE.Vector3) =>
    out
      .copy(bolt.start)
      .multiplyScalar((1 - t) * (1 - t))
      .addScaledVector(bolt.middle, 2 * (1 - t) * t)
      .addScaledVector(orbPosition, t * t);

  function updateBolt(bolt: Bolt, delta: number) {
    if (!bolt.isFlying) return;
    bolt.progress += delta / BOLT_SECONDS;
    const hasLanded = bolt.progress >= 1;
    [bolt.head, ...bolt.trail].forEach((sprite, k) => {
      const t = bolt.progress - k * 0.05;
      sprite.visible = !hasLanded && t > 0;
      if (sprite.visible) sprite.position.copy(bezier(bolt, t, boltPosition));
    });
    if (hasLanded) {
      bolt.isFlying = false;
      // the orb drinks the spell in and swells for a moment
      state.orbPower = Math.min(2.2, state.orbPower + 0.3);
      impact.material.color.copy(bolt.head.material.color);
      impactAge = 0;
    }
  }

  function pickLookTarget(wizard: Wizard, time: number) {
    const roll = Math.random();
    const others = slots.filter(
      (other): other is Wizard => !!other && other !== wizard,
    );
    if (roll < 0.25) wizard.lookTarget.copy(camera.position);
    else if (roll < 0.45 && others.length) {
      const other = others[Math.floor(Math.random() * others.length)];
      other.group.getWorldPosition(wizard.lookTarget);
      wizard.lookTarget.y += HEAD_HEIGHT * WIZARD_SCALE;
    } else wizard.lookTarget.copy(orbPosition);
    wizard.lookUntil = time + 3 + Math.random() * 4;
  }

  /** Turns the neck and head towards the look target, on top of whatever clip is playing. */
  function updateLook(wizard: Wizard, delta: number, time: number) {
    if (time >= wizard.lookUntil) pickLookTarget(wizard, time);
    scratch.copy(wizard.lookTarget);
    wizard.group.worldToLocal(scratch);
    scratch.y -= HEAD_HEIGHT;
    const yaw = THREE.MathUtils.clamp(
      Math.atan2(scratch.x, scratch.z),
      -1.1,
      1.1,
    );
    const pitch = THREE.MathUtils.clamp(
      -Math.atan2(scratch.y, Math.hypot(scratch.x, scratch.z)),
      -0.6,
      0.5,
    );
    const ease = Math.min(1, delta * 4);
    wizard.lookYaw += (yaw - wizard.lookYaw) * ease;
    wizard.lookPitch += (pitch - wizard.lookPitch) * ease;
    wizard.lookWeight +=
      ((wizard.oneShot ? 0.25 : 1) - wizard.lookWeight) * ease;
    const weight = wizard.lookWeight;
    lookTurn.setFromEuler(
      lookEuler.set(
        wizard.lookPitch * 0.35 * weight,
        wizard.lookYaw * 0.4 * weight,
        0,
      ),
    );
    wizard.bones.neck.quaternion.multiply(lookTurn);
    lookTurn.setFromEuler(
      lookEuler.set(
        wizard.lookPitch * 0.45 * weight,
        wizard.lookYaw * 0.5 * weight,
        0,
      ),
    );
    wizard.bones.head.quaternion.multiply(lookTurn);
  }

  /** Keeps the Mage's hand flame burning straight up, however the hand is turned, and licking. */
  function updateFlame(flame: THREE.Bone, time: number) {
    flame.parent!.getWorldQuaternion(flameTurn).invert();
    flame.quaternion.setFromUnitVectors(
      FORWARD,
      scratch.set(0, 1, 0).applyQuaternion(flameTurn),
    );
    flame.scale.set(
      1 + 0.12 * Math.sin(time * 13),
      1 + 0.12 * Math.sin(time * 17 + 2),
      1 + 0.2 * Math.sin(time * 11 + 1) + 0.1 * Math.sin(time * 23.7),
    );
  }

  function updateGlows(wizard: Wizard, time: number) {
    // the casting focus brightens through the wind-up and fades after the release
    let charge = 0;
    if (wizard.oneShot === wizard.cast) {
      const castTime = wizard.cast.time;
      charge =
        castTime < CAST_RELEASE_SECONDS
          ? smoothstep(castTime / CAST_RELEASE_SECONDS)
          : 1 - smoothstep((castTime - CAST_RELEASE_SECONDS) / 0.35);
    }
    const { castGlow } = wizard;
    const shimmer = 1 + 0.08 * Math.sin(time * 5 + wizard.phase);
    castGlow.sprite.scale.setScalar(
      castGlow.anchor.size * shimmer * (1 + charge * 2.2),
    );
    castGlow.sprite.material.color
      .copy(castGlow.baseColor)
      .multiplyScalar(1 + charge * 2.5);
    wizard.extraGlows.forEach(({ sprite, anchor, baseColor }, k) => {
      const flicker = anchor.flickers
        ? 0.82 +
          0.18 * Math.sin(time * 11 + wizard.phase + k * 2) +
          0.1 * Math.sin(time * 23.7 + k)
        : 0.94 + 0.06 * Math.sin(time * 2.2 + wizard.phase + k);
      sprite.scale.setScalar(anchor.size * flicker);
      sprite.material.color.copy(baseColor).multiplyScalar(flicker);
    });
    if (wizard.shield)
      wizard.shield.material.opacity =
        0.26 + 0.08 * Math.sin(time * 1.8 + wizard.phase);
    const flashFade = Math.max(0, 1 - wizard.age / 0.7);
    wizard.flash.visible = flashFade > 0;
    wizard.flash.scale.setScalar(1.2 + (1 - flashFade) * 2.6);
    wizard.flash.material.opacity = flashFade * 0.9;
  }

  function updateWizard(wizard: Wizard, { delta, elapsed }: FrameTime) {
    wizard.age += delta;
    const appear = Math.min(1, wizard.age / APPEAR_SECONDS);
    wizard.group.scale.setScalar(
      WIZARD_SCALE *
        Math.max(0.05, reducedMotion ? appear : easeOutBack(appear)),
    );

    // The mixer only rewrites a bone when its animated value changes, so take last frame's
    // look back off first; otherwise it would pile up on a bone the clip is holding still.
    wizard.bones.neck.quaternion.copy(wizard.animatedNeck);
    wizard.bones.head.quaternion.copy(wizard.animatedHead);
    wizard.mixer.update(delta);
    wizard.animatedNeck.copy(wizard.bones.neck.quaternion);
    wizard.animatedHead.copy(wizard.bones.head.quaternion);
    if (
      wizard.oneShot === wizard.cast &&
      !wizard.hasReleasedSpell &&
      wizard.cast.time >= CAST_RELEASE_SECONDS
    ) {
      wizard.hasReleasedSpell = true;
      releaseSpell(wizard);
    }
    if (!wizard.oneShot && elapsed >= wizard.nextIdleBreakAt)
      playOnce(
        wizard,
        wizard.isShowingOff || Math.random() < 0.65
          ? wizard.cast
          : wizard.flourish,
      );

    updateLook(wizard, delta, elapsed);
    wizard.group.updateMatrixWorld(true);
    const gust = reducedMotion ? 0.3 : 1;
    wind.set(
      (0.12 + 0.2 * Math.sin(elapsed * 1.3 + wizard.phase)) * gust,
      0,
      (-0.1 + 0.16 * Math.sin(elapsed * 0.9 + wizard.phase * 1.7)) * gust,
    );
    wizard.springs.update(delta, wind);
    if (wizard.classId === "mage") updateFlame(wizard.bones.flameL, elapsed);
    updateGlows(wizard, elapsed);
    updateBolt(wizard.bolt, delta);
  }

  return {
    /** Puts a wizard of the given class on a casting circle, or clears the circle. */
    setWizard(circleIndex: number, classId: WizardClassId | null) {
      const current = slots[circleIndex];
      if ((current?.classId ?? null) === classId) return;
      if (current) remove(current);
      const wizard = classId ? spawn(circleIndex, classId) : null;
      slots[circleIndex] = wizard;
      if (!wizard) return;
      circles[circleIndex].flashTime = state.time;
      // everyone already in the arena turns to watch the newcomer arrive
      slots.forEach((other) => {
        if (!other || other === wizard) return;
        wizard.group.getWorldPosition(other.lookTarget);
        other.lookTarget.y += HEAD_HEIGHT * WIZARD_SCALE;
        other.lookUntil = state.time + 2.5;
      });
    },

    /** Makes the wizard on a circle cast now. Returns false when there is none or they are busy. */
    castSpell(circleIndex: number) {
      const wizard = slots[circleIndex];
      if (!wizard || wizard.oneShot) return false;
      playOnce(wizard, wizard.cast);
      return true;
    },

    /** Called when a newly chosen wizard releases the first spell. */
    setShowOffCastListener(listener: ((circleIndex: number) => void) | null) {
      onShowOffCast = listener;
    },

    update(frame: FrameTime) {
      arena.localToWorld(orbPosition.set(0, ORB_Y, 0));
      slots.forEach((wizard) => {
        if (wizard) updateWizard(wizard, frame);
      });
      if (impactAge < 1) {
        impactAge = Math.min(1, impactAge + frame.delta / 0.35);
        impact.visible = impactAge < 1;
        impact.position.copy(orbPosition);
        impact.scale.setScalar(3 + impactAge * 7);
        impact.material.opacity = 1 - impactAge;
      }
    },

    /** Shows one wizard so its shaders compile with the rest of the world, before anyone picks. */
    prewarm() {
      const wizard = spawn(0, "guardian");
      wizard.isShowingOff = false;
      wizard.group.scale.setScalar(WIZARD_SCALE);
      slots[0] = wizard;
    },
    endPrewarm() {
      if (slots[0]) remove(slots[0]);
      slots[0] = null;
    },

    dispose() {
      slots.forEach((wizard, i) => {
        if (wizard) remove(wizard);
        slots[i] = null;
      });
      geometries.forEach((geometry) => geometry.dispose());
      materials.forEach((material) => material.dispose());
      painted.forEach(({ texture, materials: classMaterials }) => {
        classMaterials.slice(0, 2).forEach((material) => material.dispose());
        texture.dispose();
      });
      painted.clear();
      shieldGeometry.dispose();
      shieldRimGeometry.dispose();
      impact.removeFromParent();
      impact.material.dispose();
    },
  };
}
